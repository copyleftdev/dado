#!/usr/bin/env python3
"""Projections for a Dado cluster: what a configuration needs, weighs, draws
and might cost to print. Run it to regenerate README.md beside it.

Every figure here is calculated or assumed, none is measured: nothing has
been printed. The inputs and where each comes from are listed below."""

# Solid volume of each part in cm3, as the CAD kernel reports it.
VOLUME = {"cell": 73.06, "carrier": 15.86, "base": 64.31, "top cap": 17.38, "side cap, rail": 10.74,
          "side cap, lips": 11.08, "bay": 247.33, "shelf": 50.40, "tall bay": 340.37, "tall shelf": 72.75,
          "rack bay": 491.05, "rack shelf": 97.48}
DENSITY = 1.01           # g/cm3: PA12 nylon, powder-bed printed
FITTED = 0.11            # kg in each cell besides print: Pi 5, Active Cooler, PoE HAT, fan, screws (assumed)
WATTS = {"idle": 3.9, "typical": 6.2, "flat out": 14.3}  # per node at the switch: published Pi 5 figures, plus 15 % PoE loss and a 0.5 W fan
PRINT_RATE = (0.275, 0.52)  # US$ a gram, low and high: bureau prices for PA12 collected in November 2026
PITCH, RISE, GAP = 70.6, 45.6, 3.6
BAYS = {None: (0, 0, None, None), "bay": (3, 1, "bay", "shelf"), "tall bay": (3, 2, "tall bay", "tall shelf"),
        "rack bay": (4, 2, "rack bay", "rack shelf")}
CONFIGS = [("One", 1, 1, None), ("Trio", 3, 1, None), ("Six and a bay", 3, 2, "bay"), ("Nine", 3, 3, None),
           ("Nine and a bay", 3, 3, "bay"), ("Twelve and a rack bay", 4, 3, "rack bay"),
           ("Twenty-four and two bays", 6, 4, "bay"), ("A hundred", 10, 10, None)]


def project(cols, rows, bay):
    wide, up, body, shelf = BAYS[bay]
    crowns = cols // wide if wide and cols % wide == 0 else 0
    high = rows + (up if crowns else 0)
    n = cols * rows
    parts = {"cell": n, "carrier": n, "base": cols, "top cap": cols, "side cap, rail": high, "side cap, lips": high}
    if crowns:
        parts[body], parts[shelf] = crowns, crowns
    grams = sum(VOLUME[k] * v for k, v in parts.items()) * DENSITY
    return {"nodes": n, "parts": parts, "printed_kg": grams / 1000, "loaded_kg": grams / 1000 + n * FITTED,
            "width_mm": cols * PITCH - GAP + 11.2, "height_mm": high * RISE + 28.6,
            "watts": {k: w * n for k, w in WATTS.items()}, "ports": n + 1,
            "print_usd": tuple(grams * r for r in PRINT_RATE), "bays": crowns}


def main():
    rows = ["| Configuration | Pis | Size, mm | Printed | Loaded | Typical | Flat out | Switch ports | Print cost |",
            "|---|---|---|---|---|---|---|---|---|"]
    for name, cols, high, bay in CONFIGS:
        p = project(cols, high, bay)
        rows.append(f"| {name} ({cols} by {high}) | {p['nodes']} | {p['width_mm']:.0f} by {p['height_mm']:.0f} by 110 | "
                    f"{p['printed_kg']:.2f} kg | {p['loaded_kg']:.1f} kg | {p['watts']['typical']:.0f} W | "
                    f"{p['watts']['flat out']:.0f} W | {p['ports']} | ${p['print_usd'][0]:,.0f} to ${p['print_usd'][1]:,.0f} |")
    text = f"""# Projections

Generated by `projections.py`. **Every figure is calculated or assumed; none is measured. Nothing has been printed.**

{chr(10).join(rows)}

## What the columns mean

- **Size** is the assembled wall with its bases and caps; depth includes the pull and the latch fingers.
- **Printed** is the mass of the printed parts alone: kernel volume times {DENSITY} g/cm3 for PA12 nylon.
- **Loaded** adds {FITTED * 1000:.0f} g a cell for the Pi 5, Active Cooler, PoE HAT, fan and screws. That allowance is assumed.
- **Typical** and **flat out** are power at the switch: {WATTS['typical']} W and {WATTS['flat out']} W a node, from published Raspberry Pi 5
  measurements with 15 % added for PoE conversion and 0.5 W for the fan. Idle is {WATTS['idle']} W a node. The flat-out figure is
  also the PoE budget the switches must cover, and every port must be PoE+ (802.3at).
- **Switch ports** is one a Pi and one uplink. An eight-port switch serves seven Pis; a bay holds one such switch.
- **Print cost** is printed mass at ${PRINT_RATE[0]} to ${PRINT_RATE[1]} a gram, the range of bureau prices for powder-bed PA12
  collected in November 2026. It covers printing only: no Pis, HATs, fans, switches, screws or finishing.

## What these do not tell you

- Whether the parts print within tolerance. The joints were simulated at +/-0.30 mm; a printed sample is the test.
- Whether a cell stays cool. The 25 mm fan's effect is not modelled.
- Whether a hundred is sound as drawn. A wall ten high needs a deeper base than the desk-scale one here.
- What a moulded part would cost. These are printing prices at quantities of one to a few hundred.
"""
    open(__file__.replace("projections.py", "README.md"), "w").write(text)
    print(text)


if __name__ == "__main__":
    main()
